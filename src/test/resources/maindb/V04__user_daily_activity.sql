CREATE TABLE user_daily_activity
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT NOT NULL,
    activity_date DATE   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_user_daily_activity_date_user
        UNIQUE (activity_date, user_id)
);
